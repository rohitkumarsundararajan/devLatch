package report

import (
	"fmt"
	"io"
	"strings"

	"github.com/rohitkumarsundararajan/devlatch/internal/diff"
)

// Marker is a hidden HTML comment at the top of the report. CI uses it to
// find and update its own PR comment instead of posting a new one each run.
const Marker = "<!-- devlatch-report -->"

func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	s = strings.ReplaceAll(s, "\n", " ")
	return s
}

func mdDetail(v diff.Violation) string {
	var parts []string
	if len(v.Expected) > 0 {
		parts = append(parts, "expected "+strings.Join(v.Expected, "|"))
	}
	if len(v.Actual) > 0 {
		parts = append(parts, "got "+strings.Join(v.Actual, "|"))
	}
	if v.RenameFrom != "" {
		parts = append(parts, fmt.Sprintf("`%s` -> `%s`, confidence %.2f", v.RenameFrom, v.RenameTo, v.Confidence))
	}
	if len(v.Evidence) > 0 {
		parts = append(parts, "evidence: "+strings.Join(v.Evidence, "; "))
	}
	return cell(strings.Join(parts, "; "))
}

// Markdown writes a PR-comment-ready report: a status line and a table.
func Markdown(w io.Writer, vs []diff.Violation) {
	_, _ = fmt.Fprintln(w, Marker)
	_, _ = fmt.Fprintln(w, "## DevLatch API contract check")
	_, _ = fmt.Fprintln(w)
	if len(vs) == 0 {
		_, _ = fmt.Fprintln(w, "**OK**: no drift detected. Traffic matches the approved contract.")
		return
	}
	b, wn, s := Count(vs)
	status := "**OK**: only safe changes"
	if b > 0 {
		status = "**FAILED**: breaking drift detected"
	} else if wn > 0 {
		status = "**WARNING**: non-breaking drift detected"
	}
	_, _ = fmt.Fprintf(w, "%s (%d breaking, %d warning, %d safe)\n\n", status, b, wn, s)
	_, _ = fmt.Fprintln(w, "| Severity | Endpoint | Path | Change | Details |")
	_, _ = fmt.Fprintln(w, "|---|---|---|---|---|")
	for _, v := range vs {
		_, _ = fmt.Fprintf(w, "| %s | `%s` | `%s` | %s | %s |\n",
			cell(fmt.Sprint(v.Severity)), cell(v.Endpoint), cell(v.Path), cell(fmt.Sprint(v.Type)), mdDetail(v))
	}
	_, _ = fmt.Fprintln(w)
	_, _ = fmt.Fprintln(w, "<sub>Generated by DevLatch</sub>")
}
